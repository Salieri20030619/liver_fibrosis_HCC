args<-commandArgs(trailingOnly=TRUE)
root<-args[1]
lib<-file.path(root,'R_project_library_v1')
dir.create(lib,recursive=TRUE,showWarnings=FALSE)
.libPaths(c(lib,.Library))
Sys.setenv(R_LIBS_USER=lib)
options(repos=c(CRAN='https://cloud.r-project.org'),timeout=180,Ncpus=4)
cat('Project library:',lib,'\n');print(R.version.string);print(.libPaths())
install.packages(c('BiocManager','remotes'),lib=lib)
if(requireNamespace('BiocManager',quietly=TRUE)) options(repos=BiocManager::repositories())
if(requireNamespace('remotes',quietly=TRUE)) remotes::install_github('chuiqin/irGSEA',lib=lib,upgrade='never',dependencies=NA)
writeLines(capture.output(sessionInfo()),file.path(root,'R_dependencies_sessionInfo.txt'))
packages<-c('irGSEA','UCell','AUCell')
status<-data.frame(package=packages,available=vapply(packages,requireNamespace,logical(1),quietly=TRUE),version=vapply(packages,function(x)if(requireNamespace(x,quietly=TRUE))as.character(packageVersion(x))else NA_character_,character(1)))
write.table(status,file.path(root,'R_dependency_status.tsv'),sep='\t',quote=FALSE,row.names=FALSE)

